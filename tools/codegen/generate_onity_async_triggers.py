def wrap(text, indent="    ", width=DOC_WIDTH):
    """Wraps text for a '///' block at the given indentation, keeping '<see cref=...>' tags whole."""
    protected = text.replace("<see cref", "<see\x00cref")
    lines, current = [], ""
    for word in protected.split():
        candidate = word if not current else current + " " + word
        if current and len(indent) + 4 + len(candidate) > width:
            lines.append(current)
            current = word
        else:
            current = candidate
    if current:
        lines.append(current)
    return [line.replace("\x00", " ") for line in lines]


def doc_block(lines, indent="    "):
    return "\n".join(indent + "/// " + line for line in lines)


TRIGGER_TEMPLATE = Template("""#region ${name}
${define_open}
    /// <summary>
${interface_summary}
    /// </summary>
    public interface IOnityAsync${method}Handler
    {
        /// <summary>Waits for the next <c>${method}</c> message. ${thread}</summary>
        /// <returns>A single-consumption task${payload_returns}; canceled when the trigger is destroyed.</returns>
${await_remarks}        ${task_type} ${method}Async();
    }

    public sealed partial class OnityAsyncTriggerHandler<T> : IOnityAsync${method}Handler
    {
        ${task_type} IOnityAsync${method}Handler.${method}Async()
        {
            return ${wait_call};
        }
    }

    public static partial class OnityAsyncTriggerExtensions
    {
        /// <summary>Gets or adds the <see cref="OnityAsync${name}Trigger"/>. Main thread only.</summary>
        /// <param name="gameObject">Live owner GameObject.</param>
        /// <returns>The single <see cref="OnityAsync${name}Trigger"/> on the GameObject.</returns>
        /// <exception cref="ArgumentNullException"><paramref name="gameObject"/> is null.</exception>
        public static OnityAsync${name}Trigger GetAsync${name}Trigger(this GameObject gameObject)
        {
            return GetOrAddComponent<OnityAsync${name}Trigger>(gameObject);
        }

        /// <summary>Gets or adds the <see cref="OnityAsync${name}Trigger"/> on the component's GameObject. Main thread only.</summary>
        /// <param name="component">Live owner component.</param>
        /// <returns>The single <see cref="OnityAsync${name}Trigger"/> on the GameObject.</returns>
        /// <exception cref="ArgumentNullException"><paramref name="component"/> is null.</exception>
        public static OnityAsync${name}Trigger GetAsync${name}Trigger(this Component component)
        {
            return GetGameObject(component).GetAsync${name}Trigger();
        }
    }

    /// <summary>
${class_summary}
    /// </summary>
${class_remarks}    [DisallowMultipleComponent]
    public sealed class OnityAsync${name}Trigger : OnityAsyncTriggerBase<${payload}>
    {
${constructor}        /// <summary>Creates a reusable handler; dispose it to unregister. ${thread}</summary>
        /// <returns>A handler whose each <c>${method}Async()</c> waits for the next message.</returns>
        public IOnityAsync${method}Handler Get${method}AsyncHandler()
        {
            return new OnityAsyncTriggerHandler<${payload}>(this, false);
        }

        /// <summary>Creates a reusable handler bound to a token. ${thread}</summary>
        /// <param name="cancellationToken">Cancels the pending wait and unregisters the handler.</param>
        /// <returns>A handler whose each <c>${method}Async()</c> waits for the next message.</returns>
        public IOnityAsync${method}Handler Get${method}AsyncHandler(CancellationToken cancellationToken)
        {
            return new OnityAsyncTriggerHandler<${payload}>(this, cancellationToken, false);
        }

        /// <summary>Waits for the next <c>${method}</c> message. ${thread}</summary>
        /// <returns>A single-consumption task${payload_returns}; canceled when the trigger is destroyed.</returns>
${await_remarks}        public ${task_type} ${method}Async()
        {
            return ((IOnityAsync${method}Handler)new OnityAsyncTriggerHandler<${payload}>(this, true)).${method}Async();
        }

        /// <summary>Waits for the next <c>${method}</c> message. ${thread}</summary>
        /// <param name="cancellationToken">Cancels the wait.</param>
        /// <returns>A single-consumption task${payload_returns}; canceled by the token or when the trigger is destroyed.</returns>
${await_remarks}        public ${task_type} ${method}Async(CancellationToken cancellationToken)
        {
            return ((IOnityAsync${method}Handler)new OnityAsyncTriggerHandler<${payload}>(this, cancellationToken, true)).${method}Async();
        }

        private void ${method}(${message_parameters})
        {
            RaiseEvent(${raise_expression});
        }
    }
${define_close}#endregion
""")


def render_trigger(trigger):
    interface_text = ("Waits for the next <c>{}</c> message, which Unity sends {} "
                      "(UniTask <c>IAsync{}Handler</c> parity).").format(trigger.method, trigger.summary,
                                                                        trigger.method)
    thread = "Safe to call from any thread." if trigger.thread_safe else "Main thread only."
    class_text = ("Trigger for the <c>{}</c> message, which Unity sends {} (UniTask <c>Async{}Trigger</c> "
                  "parity). The component itself is an <see cref=\"IOnityAsyncEnumerable{{T}}\"/> of the "
                  "raised messages. {}").format(trigger.method, trigger.summary, trigger.name, thread)
    class_remarks = ""
    if trigger.remarks:
        class_remarks = ("    /// <remarks>\n" + doc_block(wrap(trigger.remarks)) + "\n    /// </remarks>\n")
    payload_returns = "" if trigger.is_unit else " completed with " + trigger.payload_doc
    await_remarks = ""
    if trigger.await_remarks:
        await_remarks = ("        /// <remarks>\n"
                         + doc_block(wrap(trigger.await_remarks, "        "), "        ")
                         + "\n        /// </remarks>\n")
    constructor = ""
    if trigger.thread_safe:
        constructor = ("        /// <summary>\n"
                       "        /// Creates the trigger with a synchronized waiter list, because Unity raises this message off the\n"
                       "        /// main thread.\n"
                       "        /// </summary>\n"
                       "        public OnityAsync{}Trigger()\n"
                       "        {{\n"
                       "            UseThreadSafeWaiters();\n"
                       "        }}\n\n").format(trigger.name)
    if trigger.define:
        define_open = "#if {}\n".format(trigger.define)
        define_close = "\n#endif\n"
    else:
        define_open = ""
        define_close = ""
    return TRIGGER_TEMPLATE.substitute(
        name=trigger.name,
        method=trigger.method,
        thread=thread,
        constructor=constructor,
        await_remarks=await_remarks,
        define_open=define_open,
        define_close=define_close,
        interface_summary=doc_block(wrap(interface_text)),
        class_summary=doc_block(wrap(class_text)),
        class_remarks=class_remarks,
        payload=trigger.payload,
        payload_returns=payload_returns,
        task_type=trigger.task_type,
        wait_call=trigger.wait_call,
        message_parameters=trigger.message_parameters,
        raise_expression=trigger.raise_expression,
    )


def generate_core():
    parts = [HEADER,
             "using System;\nusing System.Threading;\nusing Onity.Core;\nusing UnityEngine;\n\n",
             "namespace Onity.Unity.Async.Triggers\n{\n",
             "\n".join(render_trigger(trigger) for trigger in CORE_TRIGGERS),
             "}\n"]
    return "".join(parts)


