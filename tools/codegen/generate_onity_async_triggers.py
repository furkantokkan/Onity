def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="exit 1 when a generated file is stale")
    parser.add_argument("--target", choices=sorted(TARGETS) + ["all"], default="all")
    args = parser.parse_args()
    names = sorted(TARGETS) if args.target == "all" else [args.target]
    stale = False
    for name in names:
        path, generate = TARGETS[name]
        text = generate()
        if args.check:
            try:
                with open(path, "r", encoding="utf-8", newline="") as handle:
                    current = handle.read().replace("\r\n", "\n")
            except FileNotFoundError:
                current = ""
            if current != text:
                print("STALE: " + path)
                stale = True
            else:
                print("UP_TO_DATE: " + path)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print("WROTE: {} ({} lines)".format(path, text.count("\n")))
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
