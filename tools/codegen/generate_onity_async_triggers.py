#!/usr/bin/env python3
"""Generates the OnityAsync MonoBehaviour message triggers (UniTask 2.5.11 parity).

One table row per Unity message produces, for the core target (assembly Onity.Unity):
  * the handler interface  IOnityAsync<Method>Handler  with <Method>Async();
  * the explicit implementation on the partial OnityAsyncTriggerHandler<T>;
  * the GameObject / Component entry points  GetAsync<Trigger>Trigger();
  * the trigger component  OnityAsync<Trigger>Trigger  with the Unity message, the reusable-handler
    getters, and the one-shot <Method>Async() waits.
Enable, Disable, Awake, Start and Destroy are hand written (Async/Triggers and Async/OnityAsyncDestroyTrigger.cs).

Usage:
    python generate_onity_async_triggers.py            # rewrite the generated files
    python generate_onity_async_triggers.py --check    # exit 1 when a generated file is stale

Deviations from the UniTask template, on purpose:
  * ParticleUpdateJobScheduled is declared without a parameter, as Unity sends it (UniTask declares a
    ParticleSystemJobData parameter that Unity does not pass, so that trigger never fires there);
  * the audio-thread trigger (OnAudioFilterRead) synchronizes its waiter list, because Unity raises that
    message off the main thread and the usual await loop registers its next wait on the audio thread;
  * module-dependent triggers are wrapped in the symbols the Onity.Unity asmdef defines through
    versionDefines: ONITY_PHYSICS, ONITY_PHYSICS2D, ONITY_PARTICLESYSTEM;
  * like UniTask, the Mouse triggers are compiled out on iOS, Android and WSA: Unity flags every OnMouse
    handler in a handheld build, and the types would otherwise exist in every mobile project.
"""

