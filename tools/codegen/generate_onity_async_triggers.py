class Trigger:
    """One Unity message. `params` are the message parameters as (type, name) pairs."""

    def __init__(self, name, method, params, define, summary, payload_doc="", remarks="", thread_safe=False,
                 await_remarks=""):
        self.name = name
        self.method = method
        self.params = list(params)
        self.define = define  # complete #if expression, or None
        self.summary = summary
        self.payload_doc = payload_doc
        self.remarks = remarks
        self.thread_safe = thread_safe
        self.await_remarks = await_remarks  # one sentence repeated on the awaitable members

    @property
    def platform_guard(self):
        """The #if expression that applies to test code too (a Unity platform symbol), else None."""
        return self.define if self.define == HANDHELD else None

    @property
    def payload(self):
        if not self.params:
            return "Unit"
        if len(self.params) == 1:
            return self.params[0][0]
        return "(" + ", ".join("{} {}".format(t, n) for t, n in self.params) + ")"

    @property
    def is_unit(self):
        return not self.params

    @property
    def task_type(self):
        return "OnityTask" if self.is_unit else "OnityTask<{}>".format(self.payload)

    @property
    def wait_call(self):
        return "WaitAsync()" if self.is_unit else "WaitValueAsync<{}>()".format(self.payload)

    @property
    def raise_expression(self):
        if not self.params:
            return "Unit.Default"
        if len(self.params) == 1:
            return self.params[0][1]
        return "(" + ", ".join(n for _, n in self.params) + ")"

    @property
    def message_parameters(self):
        return ", ".join("{} {}".format(t, n) for t, n in self.params)


def T(name, method, params, define, summary, payload_doc="", remarks="", thread_safe=False, await_remarks=""):
    return Trigger(name, method, params, define, summary, payload_doc, remarks, thread_safe, await_remarks)


