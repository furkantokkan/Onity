# Selection, comparison and entry-point validation
# ----------------------------------------------------------------------------------------------

def select_entries(root: Path, errors: List[str]) -> List[Entry]:
    entries: List[Entry] = []
    for entry in SINGLE_FILES:
        if (root / entry.source).is_file():
            entries.append(entry)
        else:
            errors.append(f"missing source file: {entry.source}")
    for folder, recursive in FOLDERS:
        base = root / DOCS_FOLDER / folder
        for path in sorted(base.glob("**/*.md" if recursive else "*.md")):
            if path.is_file():
                relative = path.relative_to(root / DOCS_FOLDER).as_posix()
                entries.append(Entry(f"{DOCS_FOLDER}/{relative}", relative))
    return sorted(entries, key=lambda entry: entry.output)


def build(root: Path) -> Tuple[Dict[str, str], List[str], Counter]:
    """Returns ({output path: file text}, errors, link statistics)."""
    errors: List[str] = []
    entries = select_entries(root, errors)
    resolver = Resolver(root, entries, Site.load(root))
    expected: Dict[str, str] = {}
    for entry in entries:
        text = (root / entry.source).read_bytes().decode("utf-8")
        expected[entry.output] = transform(entry, text, resolver, errors)
    return expected, errors, resolver.statistics


def read_normalized(path: Path) -> Optional[str]:
    try:
        return normalize_newlines(path.read_bytes().decode("utf-8"))
    except (OSError, UnicodeDecodeError):
        return None


def first_difference(current: str, expected: str) -> int:
    current_lines = current.split("\n")
    expected_lines = expected.split("\n")
    for index in range(min(len(current_lines), len(expected_lines))):
        if current_lines[index] != expected_lines[index]:
            return index + 1
    return min(len(current_lines), len(expected_lines)) + 1


def list_files(directory: Path) -> Dict[str, Path]:
    if not directory.is_dir():
        return {}
    return {path.relative_to(directory).as_posix(): path
            for path in sorted(directory.rglob("*")) if path.is_file()}


def validate_entry_points(root: Path, shipped: Dict[str, str]) -> List[str]:
    """The root files that point at Documentation~ must name only files that exist, and llms.txt
    must list every shipped file."""
    problems: List[str] = []
    package = root / PACKAGE_PATH
    pattern = re.compile(re.escape(OUTPUT_FOLDER) + r"/[A-Za-z0-9_.\-/]*[A-Za-z0-9_\-/]")
    for name in ENTRY_POINTS:
        path = package / name
        if not path.is_file():
            if name != "README.md":
                problems.append(f"missing: {PACKAGE_PATH}/{name}")
            continue
        text = normalize_newlines(path.read_text(encoding="utf-8"))
        mentioned = set(pattern.findall(text))
        for reference in sorted(mentioned):
            if not (package / reference).exists():
                problems.append(f"{PACKAGE_PATH}/{name} names {reference}, which does not exist")
        if name == INDEX_FILE:
            for output in sorted(shipped):
                if f"{OUTPUT_FOLDER}/{output}" not in mentioned:
                    problems.append(f"{PACKAGE_PATH}/{name} does not list {OUTPUT_FOLDER}/{output}")
    return problems


def remove_empty_directories(directory: Path) -> None:
    for path in sorted((p for p in directory.rglob("*") if p.is_dir()), key=lambda p: len(p.parts), reverse=True):
        if not any(path.iterdir()):
            path.rmdir()


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="Report stale, missing or extra files without writing; exit 1 if any.")
    parser.add_argument("--repo-root", default=None, help="Repository root (default: derived from this script).")
    arguments = parser.parse_args(argv)
    root = Path(arguments.repo_root).resolve() if arguments.repo_root else REPOSITORY_ROOT

    expected, errors, statistics = build(root)
    if errors:
        for error in errors:
            print(f"error: {error}")
        print("nothing was written")
        return 2

    output_root = root / PACKAGE_PATH / OUTPUT_FOLDER
    display = f"{PACKAGE_PATH}/{OUTPUT_FOLDER}"
    existing = list_files(output_root)
    problems: List[str] = []
    written = 0

    for relative, text in expected.items():
        path = output_root / relative
        current = read_normalized(path) if path.is_file() else None
        if current == text:
            continue
        if arguments.check:
            if current is None:
                problems.append(f"missing: {display}/{relative}")
            else:
                problems.append(f"stale: {display}/{relative} (first difference at line "
                                f"{first_difference(current, text)})")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.encode("utf-8"))
        written += 1
        print(f"wrote {display}/{relative}")

    removed = 0
    for relative in sorted(set(existing) - set(expected)):
        if arguments.check:
            problems.append(f"extra: {display}/{relative} is not generated from a source file")
        else:
            existing[relative].unlink()
            removed += 1
            print(f"removed {display}/{relative}")
    if removed:
        remove_empty_directories(output_root)

    out_of_date = bool(problems)
    entry_problems = validate_entry_points(root, expected)
    problems.extend(entry_problems)
    for problem in problems:
        print(problem)

    total = sum(len(text.encode("utf-8")) for text in expected.values())
    summary = f"{len(expected)} files, {total / 1024:.1f} KiB in {display}"
    if arguments.check:
        if out_of_date:
            print(f"Run python {SCRIPT_PATH} and commit the result.")
        if entry_problems:
            print("Fix the entry-point files listed above by hand; they are not generated.")
        if problems:
            return 1
        print(f"package docs are up to date ({summary})")
        return 0

    links = ", ".join(f"{count} {kind}" for kind, count in sorted(statistics.items()))
    print(f"{summary}; wrote {written}, removed {removed}; links rewritten: {links or 'none'}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
