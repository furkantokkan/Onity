# Markdown processing
# ----------------------------------------------------------------------------------------------

FENCE_OPEN = re.compile(r"^[ \t]*(`{3,}|~{3,})(.*)$")
FENCE_CLOSE = re.compile(r"^[ \t]*(`{3,}|~{3,})[ \t]*$")
REFERENCE_DEFINITION = re.compile(r"^ {0,3}\[(?:[^\]\\\n]|\\.)+\]:[ \t]*(?:<([^<>\n]*)>|(\S+))", re.M)
HTML_ATTRIBUTE = re.compile(r"""\b(?:href|src)[ \t]*=[ \t]*(?:"([^"\n]*)"|'([^'\n]*)')""", re.I)
LINK_TITLE_AND_CLOSE = re.compile(r"""[ \t\n]*(?:"[^"]*"|'[^']*'|\([^)]*\))?[ \t\n]*\)""")


def split_front_matter(text: str) -> Tuple[str, str]:
    """Returns (front matter block including its delimiter lines, body). The block is empty when absent."""
    lines = text.split("\n")
    if not lines or lines[0].rstrip() != "---":
        return "", text
    for index in range(1, len(lines)):
        if lines[index].rstrip() in ("---", "..."):
            return "\n".join(lines[:index + 1]) + "\n", "\n".join(lines[index + 1:])
    return "", text


def mask_code_spans(text: str) -> str:
    """Replaces inline code spans, backticks included, with NULs so link syntax inside them is ignored."""
    characters = list(text)
    length = len(text)
    index = 0
    while index < length:
        if text[index] != "`":
            index += 1
            continue
        start = index
        while index < length and text[index] == "`":
            index += 1
        run = index - start
        if start > 0 and text[start - 1] == "\\":
            continue
        close = -1
        search = index
        while search < length:
            if text[search] != "`":
                search += 1
                continue
            end = search
            while end < length and text[end] == "`":
                end += 1
            if end - search == run:
                close = end
                break
            search = end
        if close == -1:
            continue
        for position in range(start, close):
            characters[position] = "\0"
        index = close
    return "".join(characters)


def has_opening_bracket(masked: str, closing_index: int) -> bool:
    """True when the ']' at closing_index closes a '[' earlier in the paragraph."""
    depth = 1
    for index in range(closing_index - 1, -1, -1):
        character = masked[index]
        if character not in "[]":
            continue
        backslashes = 0
        while index - 1 - backslashes >= 0 and masked[index - 1 - backslashes] == "\\":
            backslashes += 1
        if backslashes % 2 == 1:
            continue
        depth += 1 if character == "]" else -1
        if depth == 0:
            return True
    return False


def destination_spans(masked: str) -> List[Tuple[int, int]]:
    """Spans of the link destinations in a masked paragraph: inline links, images, reference
    definitions and href/src attributes."""
    spans: Set[Tuple[int, int]] = set()
    length = len(masked)

    for marker in re.finditer(r"\]\(", masked):
        if not has_opening_bracket(masked, marker.start()):
            continue
        index = marker.end()
        while index < length and masked[index] in " \t":
            index += 1
        if index < length and masked[index] == "<":
            close = masked.find(">", index + 1)
            if close == -1 or "\n" in masked[index:close]:
                continue
            start, end = index + 1, close
            rest = close + 1
        else:
            depth = 0
            end = index
            while end < length:
                if masked.startswith(("{{", "{%"), end):
                    # Jekyll renders Liquid before Markdown, so an expression is part of the destination.
                    close = masked.find("}}" if masked[end + 1] == "{" else "%}", end + 2)
                    if close == -1:
                        break
                    end = close + 2
                    continue
                character = masked[end]
                if character in " \t\n":
                    break
                if character == "(":
                    depth += 1
                elif character == ")":
                    if depth == 0:
                        break
                    depth -= 1
                end += 1
            start = index
            rest = end
        if LINK_TITLE_AND_CLOSE.match(masked, rest):
            spans.add((start, end))

    for pattern in (REFERENCE_DEFINITION, HTML_ATTRIBUTE):
        for match in pattern.finditer(masked):
            group = next((number for number in (1, 2) if match.group(number) is not None), None)
            if group is not None:
                spans.add(match.span(group))

    return sorted(spans)


def rewrite_paragraph(entry: Entry, text: str, first_line: int, resolver: Resolver, errors: List[str]) -> str:
    masked = mask_code_spans(text)
    result = text
    for start, end in reversed(destination_spans(masked)):
        destination = text[start:end]
        try:
            replacement = resolver.rewrite(entry, destination)
        except LinkError as error:
            line = first_line + text.count("\n", 0, start)
            errors.append(f"{entry.source}:{line}: {error}")
            continue
        if replacement != destination:
            result = result[:start] + replacement + result[end:]

    leftover = mask_code_spans(result)
    for marker in ("{{", "{%"):
        position = leftover.find(marker)
        if position != -1:
            line = first_line + result.count("\n", 0, position)
            errors.append(f"{entry.source}:{line}: Liquid '{marker}' outside a code block or code span; "
                          "the package copy is not rendered, so escape it or remove it")
            break
    return result


def rewrite_links(entry: Entry, body: str, first_line: int, resolver: Resolver, errors: List[str]) -> str:
    """Rewrites links in the prose of a Markdown body. Fenced code blocks are copied unchanged."""
    output: List[str] = []
    paragraph: List[Tuple[int, str]] = []
    fence: Optional[Tuple[str, int]] = None

    def flush() -> None:
        if not paragraph:
            return
        text = "\n".join(line for _, line in paragraph)
        output.extend(rewrite_paragraph(entry, text, paragraph[0][0], resolver, errors).split("\n"))
        paragraph.clear()

    for offset, line in enumerate(body.split("\n")):
        number = first_line + offset
        if fence is not None:
            output.append(line)
            closing = FENCE_CLOSE.match(line)
            if closing and closing.group(1)[0] == fence[0] and len(closing.group(1)) >= fence[1]:
                fence = None
            continue
        opening = FENCE_OPEN.match(line)
        if opening and not (opening.group(1)[0] == "`" and "`" in opening.group(2)):
            flush()
            fence = (opening.group(1)[0], len(opening.group(1)))
            output.append(line)
        elif line.strip() == "":
            flush()
            output.append(line)
        else:
            paragraph.append((number, line))
    flush()
    return "\n".join(output)


def normalize_newlines(text: str) -> str:
    if text.startswith(BYTE_ORDER_MARK):
        text = text[1:]
    return text.replace("\r\n", "\n").replace("\r", "\n")


def transform(entry: Entry, text: str, resolver: Resolver, errors: List[str]) -> str:
    text = normalize_newlines(text)
    text = LIQUID_RAW_TAG.sub("", text)
    front_matter, body = split_front_matter(text)
    body = rewrite_links(entry, body, front_matter.count("\n") + 1, resolver, errors)
    body = body.lstrip("\n")
    header = GENERATED_HEADER.format(source=entry.source)
    if entry.keep_front_matter and front_matter:
        text = front_matter + "\n" + header + "\n\n" + body
    else:
        text = header + "\n\n" + body
    return text.rstrip("\n") + "\n"


