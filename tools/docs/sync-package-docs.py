#!/usr/bin/env python3
"""Generates the AI-readable documentation copy that ships inside the Onity UPM package.

Users install Onity from GitHub (the `upm` branch, or `?path=/Packages/com.onity.framework`), so only the
package folder reaches their project. The guides under `docs/` and the agent skill under `.agents/skills/`
live outside it. This script derives a copy under `Packages/com.onity.framework/Documentation~/`, a folder
that Unity ignores (no .meta files, nothing imported or compiled), where AI coding assistants can read it.

`docs/` and `.agents/skills/` stay the single source of truth. Never edit `Documentation~/` by hand: the
whole folder belongs to this script, and files it does not generate are removed.

Layout (source -> `Documentation~/`):

    docs/Onity-AI-Usage-Guide.md           AI/Onity-AI-Usage-Guide.md
    .agents/skills/onity-use/SKILL.md      AI/skills/onity-use/SKILL.md
    docs/Getting-Started.md                Getting-Started.md
    docs/guide/*.md                        guide/*.md
    docs/Migration/*.md                    Migration/*.md
    docs/reference/**/*.md                 reference/**/*.md

Everything else under docs/ (Plan, benchmarks, assets, ADR, site configuration) is not shipped.

Transformations applied to each file:

  * Jekyll front matter is removed. The skill keeps its front matter, which is the skill's own metadata.
  * A one-line HTML comment naming the source file is added at the top (after the skill's front matter).
  * Relative links are rewritten. A link to a shipped file becomes a relative `.md` path inside
    `Documentation~/` (`guide/reactive.html#x` -> `../guide/reactive.md#x`). A link to a docs-site page or
    asset that is not shipped becomes an absolute docs-site URL, and a link to any other repository file
    becomes a GitHub URL. Links into the package folder become package-relative paths. The skill is copied
    out of the package into user projects, so its links always become absolute URLs.
  * Jekyll Liquid link forms (`{{ site.baseurl }}/x.html`, `{% link x.md %}`) are resolved the same way, and
    `{% raw %}` tags are dropped. Any other Liquid is an error, because the package copy is never rendered.

Usage:

    python tools/docs/sync-package-docs.py          # write the package copy
    python tools/docs/sync-package-docs.py --check  # exit 1 when the committed copy is stale

The output depends only on the sources, so it is reproducible. Files are written with LF line endings;
the check ignores carriage returns added by a Git checkout. Generation writes nothing and exits 2 when a
link cannot be resolved.

The check also verifies the hand-written entry points at the package root (README.md, AGENTS.md,
CLAUDE.md, llms.txt): every `Documentation~/...` path they mention must exist, and llms.txt must list
every shipped file.
"""

from __future__ import annotations

import argparse
import posixpath
import re
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple
from urllib.parse import quote

REPOSITORY_ROOT = Path(__file__).resolve().parents[2]

SCRIPT_PATH = "tools/docs/sync-package-docs.py"
PACKAGE_PATH = "Packages/com.onity.framework"
OUTPUT_FOLDER = "Documentation~"
DOCS_FOLDER = "docs"
SITE_CONFIG = "docs/_config.yml"

# Used when docs/_config.yml does not define the value.
DEFAULT_SITE_URL = "https://furkantokkan.github.io"
DEFAULT_BASE_URL = "/Onity"
DEFAULT_REPOSITORY = "furkantokkan/Onity"
DEFAULT_BRANCH = "main"

GENERATED_HEADER = (
    "<!-- Generated by " + SCRIPT_PATH + " from {source}. "
    "Do not edit; change the source and re-run the script. -->"
)

# Hand-written files at the package root that point at the shipped copy.
ENTRY_POINTS = ("README.md", "AGENTS.md", "CLAUDE.md", "llms.txt")
INDEX_FILE = "llms.txt"

BYTE_ORDER_MARK = chr(0xFEFF)


@dataclass(frozen=True)
class Entry:
    """One file shipped in Documentation~."""

    source: str  # repository-relative path, forward slashes
    output: str  # path relative to Documentation~
    keep_front_matter: bool = False  # the front matter is metadata the consumer reads, not Jekyll's
    portable: bool = False  # copied out of the package, so links must not depend on its layout


SINGLE_FILES = (
    Entry("docs/Onity-AI-Usage-Guide.md", "AI/Onity-AI-Usage-Guide.md"),
    Entry(".agents/skills/onity-use/SKILL.md", "AI/skills/onity-use/SKILL.md",
          keep_front_matter=True, portable=True),
    Entry("docs/Getting-Started.md", "Getting-Started.md"),
)

# (folder under docs/, include subfolders). Each file keeps its path relative to docs/.
FOLDERS = (("guide", False), ("Migration", False), ("reference", True))


class LinkError(Exception):
    """A link that cannot be resolved to a shipped file, a docs-site page or a repository file."""


# ----------------------------------------------------------------------------------------------
# Site configuration and link targets
# ----------------------------------------------------------------------------------------------

def config_scalar(text: str, key: str) -> Optional[str]:
    """Value of a top-level `key: value` line; None when the key is absent, "" when it is empty."""
    match = re.search(r"^" + re.escape(key) + r":[ \t]*(?:\"([^\"]*)\"|'([^']*)'|([^#\r\n]*))", text, re.M)
    if not match:
        return None
    return next((group for group in match.groups() if group is not None), "").strip()


def config_list(text: str, key: str) -> List[str]:
    lines = text.splitlines()
    items: List[str] = []
    for index, line in enumerate(lines):
        if not re.match(r"^" + re.escape(key) + r":[ \t]*(#.*)?$", line):
            continue
        for item in lines[index + 1:]:
            match = re.match(r"^[ \t]+-[ \t]+(?:\"([^\"]*)\"|'([^']*)'|([^#\s]+))", item)
            if match:
                items.append(next(group for group in match.groups() if group is not None))
            elif item.strip() == "" or item.lstrip().startswith("#"):
                continue
            else:
                break
        break
    return items


@dataclass(frozen=True)
class Site:
    """Where the Jekyll docs site and the GitHub repository live, read from docs/_config.yml."""

    url: str  # site URL plus base path, no trailing slash
    base_path: str
    repository: str
    branch: str
    excludes: Tuple[str, ...]

    @staticmethod
    def load(root: Path) -> "Site":
        config = root / SITE_CONFIG
        text = config.read_text(encoding="utf-8") if config.is_file() else ""
        site_url = (config_scalar(text, "url") or DEFAULT_SITE_URL).rstrip("/")
        configured_base = config_scalar(text, "baseurl")
        base_path = (DEFAULT_BASE_URL if configured_base is None else configured_base).strip("/")
        base_path = "/" + base_path if base_path else ""
        return Site(
            url=site_url + base_path,
            base_path=base_path,
            repository=config_scalar(text, "repository") or DEFAULT_REPOSITORY,
            branch=config_scalar(text, "gh_edit_branch") or DEFAULT_BRANCH,
            excludes=tuple(config_list(text, "exclude")),
        )

    def serves(self, relative: str) -> bool:
        """True when Jekyll publishes the docs-relative path."""
        if any(part.startswith(("_", ".")) for part in relative.split("/")):
            return False
        for pattern in self.excludes:
            excluded = pattern.rstrip("/")
            if relative == excluded or relative.startswith(excluded + "/"):
                return False
        return True

    def page_url(self, relative: str, is_page: bool) -> str:
        """URL of a docs-relative file. A Markdown file with front matter is rendered as an HTML page."""
        if is_page:
            relative = relative[:-len(".md")] + ".html"
            if relative == "index.html" or relative.endswith("/index.html"):
                relative = relative[:-len("index.html")]
        return self.url + "/" + quote(relative, safe="/")

    def repository_url(self, path: str, is_directory: bool) -> str:
        kind = "tree" if is_directory else "blob"
        return f"https://github.com/{self.repository}/{kind}/{self.branch}/{quote(path, safe='/')}"


def has_front_matter(path: Path) -> bool:
    with path.open("rb") as handle:
        return handle.read(4) in (b"---\n", b"---\r")


def relative_posix(target: str, start_directory: str) -> str:
    """Relative path from a directory to a file; both are forward-slash paths under one root."""
    target_parts = target.split("/")
    start_parts = [part for part in start_directory.split("/") if part]
    common = 0
    while (common < len(start_parts) and common < len(target_parts) - 1
           and start_parts[common] == target_parts[common]):
        common += 1
    return "/".join([".."] * (len(start_parts) - common) + target_parts[common:])


EXTERNAL_DESTINATION = re.compile(r"^(?:[A-Za-z][A-Za-z0-9+.\-]*:|//)")
LIQUID_LINK_TAG = re.compile(r"\{%-?\s*link\s+(\S+?)\s*-?%\}")
LIQUID_OUTPUT = re.compile(r"\{\{-?\s*(.*?)\s*-?\}\}")
LIQUID_FILTERED_PATH = re.compile(r"""^(['"])(.*?)\1\s*\|\s*(?:relative_url|absolute_url)$""")
LIQUID_SITE_VALUES = ("site.url", "site.baseurl", "site.url | append: site.baseurl")
LIQUID_RAW_TAG = re.compile(r"\{%-?\s*(?:end)?raw\s*-?%\}")


def resolve_liquid(path: str) -> str:
    """Turns a Jekyll Liquid link into a site-absolute path, or raises LinkError."""
    path = LIQUID_LINK_TAG.sub(lambda match: "/" + match.group(1).lstrip("/"), path)

    def output(match: "re.Match[str]") -> str:
        expression = match.group(1)
        if expression in LIQUID_SITE_VALUES:
            return ""
        filtered = LIQUID_FILTERED_PATH.match(expression)
        if filtered:
            return filtered.group(2)
        raise LinkError(f"unsupported Liquid expression '{{{{ {expression} }}}}' in a link")

    path = LIQUID_OUTPUT.sub(output, path)
    if "{%" in path or "{{" in path:
        raise LinkError(f"unsupported Liquid tag in link '{path}'")
    if not path.startswith("/"):
        path = "/" + path
    return path


class Resolver:
    """Rewrites link destinations of one shipped file."""

    def __init__(self, root: Path, entries: List[Entry], site: Site) -> None:
        self.root = root
        self.site = site
        self.shipped: Dict[str, Entry] = {entry.source: entry for entry in entries}
        self.statistics: Counter = Counter()

    def rewrite(self, entry: Entry, destination: str) -> str:
        if not destination or destination.startswith("#") or EXTERNAL_DESTINATION.match(destination):
            return destination

        path, hash_mark, fragment = destination.partition("#")
        path, question_mark, query = path.partition("?")
        suffix = question_mark + query + hash_mark + fragment
        if not path:
            return destination
        if "{{" in path or "{%" in path:
            path = resolve_liquid(path)

        if path.startswith("/"):
            site_path = path
            base = self.site.base_path
            if base and (site_path == base or site_path.startswith(base + "/")):
                site_path = site_path[len(base):]
            target = posixpath.normpath(DOCS_FOLDER + "/" + site_path.lstrip("/"))
        else:
            target = posixpath.normpath(posixpath.join(posixpath.dirname(entry.source), path))
        if target == ".." or target.startswith("../"):
            raise LinkError(f"link '{destination}' points outside the repository")

        is_directory = path.endswith("/") or (self.root / target).is_dir()
        if is_directory:
            candidates = [target + "/index.md"]
        elif target.endswith(".html"):
            candidates = [target[:-len(".html")] + ".md", target]
        else:
            candidates = [target, target + ".md"]

        if not entry.portable:
            for candidate in candidates:
                if candidate in self.shipped:
                    self.statistics["package-relative"] += 1
                    output = self.shipped[candidate].output
                    return relative_posix(output, posixpath.dirname(entry.output)) + hash_mark + fragment

        found = next((candidate for candidate in candidates if (self.root / candidate).exists()), None)
        if found is None and (self.root / target).is_dir():
            found = target
        if found is None:
            raise LinkError(f"link '{destination}' does not match a file ({target})")
        return self.external(entry, found, suffix, hash_mark + fragment)

    def external(self, entry: Entry, found: str, suffix: str, fragment: str) -> str:
        """Link to a file that is not shipped in Documentation~. The suffix is the query plus the
        fragment; a package-relative link keeps only the fragment."""
        full = self.root / found
        package_prefix = PACKAGE_PATH + "/"
        if not entry.portable and found.startswith(package_prefix):
            self.statistics["package-relative"] += 1
            output_directory = OUTPUT_FOLDER + "/" + posixpath.dirname(entry.output)
            return relative_posix(found[len(package_prefix):], output_directory) + fragment

        docs_prefix = DOCS_FOLDER + "/"
        if found.startswith(docs_prefix) and full.is_file() and self.site.serves(found[len(docs_prefix):]):
            self.statistics["docs-site"] += 1
            relative = found[len(docs_prefix):]
            is_page = relative.endswith(".md") and has_front_matter(full)
            return self.site.page_url(relative, is_page) + suffix

        self.statistics["repository"] += 1
        return self.site.repository_url(found, full.is_dir()) + suffix


